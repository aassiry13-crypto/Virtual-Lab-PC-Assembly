import { shuffle } from "./curriculum";
export interface Question {
  id: string;
  lab: number;
  kind: "choice" | "order" | "match";
  prompt: string;
  options: { id: string; text: string }[];
  answer: string[];
  explanation: string;
  image?: string;
  pairs?: string[];
}
export type PublicQuestion = Omit<Question, "answer" | "explanation">;
let seq = 0;
function q(
  lab: number,
  prompt: string,
  choices: string[],
  correct: number,
  explanation: string,
  image?: string,
): Question {
  const id = `q${++seq}`;
  return {
    id,
    lab,
    kind: "choice",
    prompt,
    options: choices.map((text, i) => ({ id: `${id}-${i}`, text })),
    answer: [`${id}-${correct}`],
    explanation,
    image,
  };
}
function arranged(
  lab: number,
  kind: "order" | "match",
  prompt: string,
  items: string[],
  explanation: string,
  pairs?: string[],
): Question {
  const id = `q${++seq}`;
  return {
    id,
    lab,
    kind,
    prompt,
    options: items.map((text, i) => ({ id: `${id}-${i}`, text })),
    answer: items.map((_, i) => `${id}-${i}`),
    explanation,
    pairs,
  };
}
