export function pickQuestions(lab: number): Question[] {
  const pool = bank.filter((q) => q.lab === lab);
  const choices = shuffle(pool.filter((q) => q.kind === "choice")).slice(0, 3);
  return shuffle([...choices, ...pool.filter((q) => q.kind !== "choice")]);
}
export function exposeQuestions(qs: Question[]): PublicQuestion[] {
  return qs.map(({ answer: _, explanation: __, ...q }) => ({
    ...q,
    options: shuffle(q.options),
  }));
}
export function grade(qs: Question[], answers: Record<string, string[]>) {
  const results = qs.map((q) => ({
    id: q.id,
    correct: JSON.stringify(q.answer) === JSON.stringify(answers[q.id]),
    explanation: q.explanation,
    correctTexts: q.answer.map(
      (id) => q.options.find((o) => o.id === id)!.text,
    ),
  }));
  return {
    score: Math.round(
      (results.filter((r) => r.correct).length / qs.length) * 100,
    ),
    results,
  };
}
