export function makeCase(
  week: number,
  stage: "discover" | "apply",
  id = crypto.randomUUID(),
): CaseState {
  const r = rows[week - 1];
  if (!r) throw new Error("أسبوع غير صالح");
  const actions: Action[] = [
    { id: "inspect-a", label: r[3], result: r[4], kind: "evidence" },
    { id: "inspect-b", label: r[5], result: r[6], kind: "evidence" },
    {
      id: "diagnose",
      label: r[7],
      result: "هذا الاستنتاج تدعمه نتائج الفحص المتاحة.",
      kind: "diagnose",
      requires: ["inspect-a", "inspect-b"],
    },
    {
      id: "repair",
      label: r[8],
      result: "تم تنفيذ الإجراء المحدد في المحاكاة. يلزم التحقق من النتيجة.",
      kind: "repair",
      requires: ["diagnose"],
    },
    {
      id: "verify",
      label: "إعادة الفحص ومقارنة النتيجة بالأعراض الأصلية",
      result: "اجتازت الحالة فحص التحقق المحدد، ولم يتكرر العطل ضمن المحاكاة.",
      kind: "verify",
      requires: ["repair"],
    },
    {
      id: "wrong-diagnosis",
      label:
        week < 12
          ? "استنتاج تلف اللوحة الأم دون فحوص إضافية"
          : "استنتاج ضرورة إعادة تثبيت النظام دون عزل السبب",
      result:
        "الأدلة لا تدعم هذا الاستنتاج. راجع نتائج الفحوص قبل تحديد السبب.",
      kind: "waste",
    },
    {
      id: "replace",
      label: "استبدال عدة قطع معًا لتجربة حل سريع",
      result: "تغيير متغيرات متعددة يمنع تحديد السبب ويضيف تكلفة غير مبررة.",
      kind: "waste",
    },
    {
      id: "unsafe",
      label:
        week <= 11
          ? "تغيير التوصيلات الداخلية والجهاز متصل بالطاقة"
          : "تهيئة قرص المستخدم قبل حفظ البيانات والتفويض",
      result:
        week <= 11
          ? "إجراء حرج: افصل التغذية قبل تغيير التوصيلات الداخلية."
          : "إجراء حرج: لا تهيّئ قرص المستخدم دون حفظ البيانات والتفويض.",
      kind: "unsafe",
    },
  ];
  return {
    id,
    week,
    stage,
    definition: {
      id: `week-${week}`,
      week,
      title: r[0],
      brief: r[1],
      image: r[2],
      actions: shuffle(actions),
    },
    done: [],
    log: [],
    mistakes: 0,
    critical: false,
    complete: false,
    passed: false,
  };
}
export function advanceCase(state: CaseState, actionId: string): CaseState {
  if (state.complete) throw new Error("انتهت المحاولة. ابدأ حالة جديدة.");
  const a = state.definition.actions.find((x) => x.id === actionId);
  if (!a) throw new Error("إجراء غير صالح");
  if (state.done.includes(a.id)) return state;
  if (a.requires?.some((id) => !state.done.includes(id)))
    return {
      ...state,
      mistakes: state.mistakes + 1,
      log: [
        ...state.log,
        {
          label: a.label,
          result:
            "الأدلة أو الخطوات السابقة غير مكتملة. أكمل الفحص والتشخيص أولًا.",
          ok: false,
        },
      ],
    };
  const bad = a.kind === "waste" || a.kind === "unsafe";
  const next = {
    ...state,
    done: bad ? state.done : [...state.done, a.id],
    mistakes: state.mistakes + (bad ? 1 : 0),
    critical: state.critical || a.kind === "unsafe",
    log: [...state.log, { label: a.label, result: a.result, ok: !bad }],
  };
  if (
    (state.stage === "discover" && a.kind === "diagnose") ||
    (state.stage === "apply" && a.kind === "verify")
  ) {
    next.complete = true;
    next.passed = !next.critical && next.mistakes <= 2;
  }
  return next;
}
export function publicCase(state: CaseState) {
  return {
    ...state,
    definition: {
      ...state.definition,
      actions: state.definition.actions
        .filter(
          (a) =>
            state.stage === "apply" || !["repair", "verify"].includes(a.kind),
        )
        .map((a) => ({
          id: a.id,
          label: a.label,
          kind:
            a.kind === "diagnose" || a.id === "wrong-diagnosis"
              ? "diagnosis"
              : a.kind === "evidence"
                ? "inspection"
                : "action",
        })),
    },
  };
}
