export interface WeekProgress {
  trained: boolean;
  discovered: boolean;
  applied: boolean;
  quizScore: number;
  mastered: boolean;
  assembly?: boolean;
  report?: string;
}
export type Progress = Record<string, WeekProgress>;
export const emptyWeek = (): WeekProgress => ({
  trained: false,
  discovered: false,
  applied: false,
  quizScore: 0,
  mastered: false,
});
export function mastery(p: WeekProgress, week: number) {
  return (
    p.trained &&
    p.discovered &&
    p.applied &&
    p.quizScore >= 80 &&
    (week !== 4 || !!p.assembly) &&
    (week < 16 || !!p.report?.trim())
  );
}
export function shuffle<T>(items: readonly T[]): T[] {
  const a = [...items];
  for (let i = a.length - 1; i > 0; i--) {
    const j = crypto.getRandomValues(new Uint32Array(1))[0] % (i + 1);
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}
